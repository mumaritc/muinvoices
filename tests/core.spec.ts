import { test, expect } from '@playwright/test'
test('edits, calculates, saves, reloads, duplicates and blocks invalid printing', async ({
  page,
}) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New invoice', exact: true }).first().click()
  await page.getByRole('button', { name: 'Details', exact: true }).click()
  await page.getByRole('button', { name: 'Company / From', exact: true }).click()
  await page
    .getByRole('textbox', { name: 'Name · English', exact: true })
    .first()
    .fill('Synthetic Studio')
  await page.getByRole('button', { name: 'Items & taxes', exact: true }).click()
  await page
    .getByRole('textbox', { name: 'Description · English', exact: true })
    .fill('Design work')
  await page.getByRole('textbox', { name: 'Unit price', exact: true }).fill('1000')
  await page.getByRole('button', { name: 'Discount', exact: true }).click()
  await page.getByRole('textbox', { name: 'Value', exact: true }).fill('10')
  await page.getByRole('button', { name: 'Named taxes', exact: true }).click()
  await page.getByRole('button', { name: 'Add named tax' }).click()
  await page.getByRole('textbox', { name: 'Name · English', exact: true }).fill('VAT')
  await page.getByRole('textbox', { name: 'Rate (%)', exact: true }).fill('15')
  await page.getByRole('button', { name: 'Line items', exact: true }).click()
  await page.getByRole('combobox', { name: 'Tax treatment' }).selectOption('taxed')
  await page.getByRole('checkbox', { name: 'VAT', exact: true }).check()
  await expect(page.getByTestId('invoice').locator('.grand-total')).toContainText('1035.00')
  await page.getByRole('button', { name: 'Save now' }).click()
  await expect(page.getByRole('status').first()).toContainText('All changes saved')
  await page.reload()
  await page.getByRole('button', { name: 'INV-2026/001', exact: false }).first().click()
  await expect(page.getByTestId('invoice').locator('.grand-total')).toContainText('1035.00')
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await expect(page.locator('.document-name')).toContainText('-copy')
  await page.getByRole('button', { name: 'Items & taxes', exact: true }).click()
  await page.getByRole('textbox', { name: 'Unit price', exact: true }).fill('invalid')
  await expect(page.getByRole('button', { name: 'Print / save PDF' })).toBeDisabled()
  await expect(page.locator('.preview-warning')).toContainText('last valid')
  await expect(page.getByTestId('invoice').locator('.grand-total')).toContainText('1035.00')
  await page.getByRole('textbox', { name: 'Unit price', exact: true }).fill('1000')
  await page.getByRole('button', { name: 'Invoices', exact: true }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete', exact: true }).first().click()
  await expect(page.getByRole('button', { name: 'Invoices 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'INV-2026/001-copy', exact: false }).first().click()
  await expect(page.getByTestId('invoice').locator('.grand-total')).toContainText('1035.00')
})
