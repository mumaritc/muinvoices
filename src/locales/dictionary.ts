export type CopyKey = keyof typeof copy
export function t(key: CopyKey, language: 'en' | 'ar') {
  return copy[key][language === 'ar' ? 1 : 0]
}
export function localizedValues(
  value: LocalizedText,
  mode: 'en' | 'ar' | 'bilingual',
  order: 'en-first' | 'ar-first',
) {
  const languages: ('en' | 'ar')[] =
    mode === 'bilingual'
      ? order === 'ar-first'
        ? ['ar', 'en']
        : ['en', 'ar']
      : [mode, mode === 'en' ? 'ar' : 'en']
  const values = languages
    .filter((l) => value[l]?.trim())
    .map((language) => ({ language, text: value[language]! }))
  return mode === 'bilingual'
    ? values.filter((v, i) => !i || v.text !== values[0].text)
    : values.slice(0, 1)
}
